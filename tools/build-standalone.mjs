// Build the single-file runtime package.
//
//     node tools/build-standalone.mjs        ->  dist/flow-studio.html
//
// WHY THIS EXISTS
// tools/flow-studio.html imports core/power-automate/studio.js as an ES module, so it needs
// to be served over HTTP: a browser refuses to fetch module specifiers from a file:// page,
// and the tool silently renders nothing. That is fine on a workstation with a server to
// hand and useless for someone who just wants the file.
//
// This inlines the whole dependency graph into one document with no imports and no external
// references, so it opens by double-clicking. The page itself is NOT duplicated — the same
// tools/flow-studio.html is the input, with its one import line replaced. There is one
// screen, one stylesheet and one generator, however the tool is delivered.
//
// The bundle is deliberately left unminified. This is an internal government platform; a
// file that gets copied onto machines and opened without review should be readable by the
// person reviewing it.
//
// esbuild is invoked through npx rather than imported. This repository has no package.json,
// no node_modules and no build step for anything else, and adding a dependency manifest so
// that one optional artifact can be produced would change how the whole project is checked
// out and served. npx fetches the tool when it is asked for and leaves nothing behind.

import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const SOURCE = path.join(repo, 'tools', 'flow-studio.html');
const OUT_DIR = path.join(repo, 'dist');
const OUT = path.join(OUT_DIR, 'flow-studio.html');
const IMPORT_LINE = "  import { createStudio } from '../core/power-automate/studio.js';";
const GLOBAL = 'FlowStudioRuntime';

/**
 * A fingerprint of what actually went into the package.
 *
 * Not the git commit: this file is built BEFORE the commit that carries it exists, so a
 * commit hash in the banner would always name the previous one — a traceability line that
 * points at the wrong thing is worse than none. Hashing the inputs is exact, and anyone
 * can re-run the build and compare the number.
 */
async function sourceFingerprint() {
  const files = [
    'tools/flow-studio.html',
    'config/power-automate.config.js',
    'config/endpoints.config.js',
    ...['index', 'studio', 'studio.css', 'catalog', 'assemble', 'validate', 'clipboard', 'blueprints', 'expressions', 'schema', 'triggers']
      .map(n => `core/power-automate/${n}.js`)
  ].sort();
  const hash = createHash('sha256');
  for (const rel of files) {
    hash.update(rel);
    hash.update(await readFile(path.join(repo, rel)));
  }
  return { digest: hash.digest('hex').slice(0, 12), count: files.length };
}

async function main() {
  const fingerprint = await sourceFingerprint();
  const entry = path.join(OUT_DIR, '.entry.js');
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(entry, "export { createStudio } from '../core/power-automate/studio.js';\n");

  let bundle;
  try {
    bundle = execFileSync('npx', [
      '--yes', 'esbuild', entry,
      '--bundle', '--format=iife', `--global-name=${GLOBAL}`,
      '--platform=browser', '--target=es2022', '--legal-comments=none'
    ], { cwd: repo, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    throw new Error(`esbuild failed. It is fetched with npx, so this needs network access the first time.\n${e.stderr || e.message}`);
  } finally {
    await rm(entry, { force: true });
  }
  // A literal </script> anywhere in the bundle would close the tag early. Nothing in the
  // sources contains one today; escaping it means nothing has to remember that tomorrow.
  bundle = bundle.replace(/<\/script/gi, '<\\/script');

  const html = await readFile(SOURCE, 'utf8');
  if (!html.includes(IMPORT_LINE)) {
    throw new Error(`tools/flow-studio.html no longer contains the expected import line:\n${IMPORT_LINE}`);
  }

  const banner = `<!--
  Flow Studio — single-file runtime package.

  GENERATED by tools/build-standalone.mjs from tools/flow-studio.html and
  core/power-automate/**. Do not edit this file; edit the sources and rebuild:

      node tools/build-standalone.mjs

  Built from ${fingerprint.count} source files, sha256 ${fingerprint.digest}.\n  Rebuild and compare that digest to confirm this file matches the repository.

  HOW TO USE
    1. Save this file anywhere and open it in Chrome or Edge. No server, no install.
    2. Build the actions you want, or load a DGO blueprint.
    3. Press "Copy for the designer".
    4. In the Power Automate designer, click the + where the actions belong and choose
       "Paste an action".

  Firefox cannot receive the paste: it does not expose navigator.clipboard.readText() to web
  pages, so the designer falls back to reading localStorage on its own origin, which nothing
  outside make.powerautomate.com can write. The page says so when opened there.

  Nothing in this file talks to a network. Plans are kept in this browser's localStorage and
  go nowhere else.
-->
`;

  const out = html
    .replace('<!doctype html>\n', `<!doctype html>\n${banner}`)
    // No imports remain, and the page has no top-level await, so a classic script is the
    // safer choice: it sidesteps any module-loading restriction a file:// page might carry.
    .replace('<script type="module">', '<script>')
    .replace(IMPORT_LINE, `${bundle}\n  const { createStudio } = ${GLOBAL};`);

  await writeFile(OUT, out);

  // Guard rails. A package that still points at a file it cannot fetch is worse than none,
  // because it fails only once it has been copied somewhere without the repo around it.
  const problems = [];
  if (/\bimport\s+[{*\w]/.test(out.replace(bundle, ''))) problems.push('an import statement survived outside the bundle');
  if (/(src|href)=["']((?!data:)[^"'#]+)["']/i.test(out)) problems.push('an external src/href reference remains');
  if (out.includes('type="module"')) problems.push('a module script tag remains');
  if (!out.includes(`const { createStudio } = ${GLOBAL};`)) problems.push('the runtime was not wired to the page');
  if (problems.length) throw new Error('Build produced an unusable package:\n  - ' + problems.join('\n  - '));

  const kb = n => `${(n / 1024).toFixed(1)} KB`;
  console.log(`dist/flow-studio.html  ${kb(Buffer.byteLength(out))}  (bundle ${kb(Buffer.byteLength(bundle))})`);
  console.log(`sources ${fingerprint.count} files · sha256 ${fingerprint.digest} — self-contained, no external references`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
